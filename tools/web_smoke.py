"""Replay actual UI smoke checks against local Flutter web release. No mocked UI.
Start http.server on 8765 and isolated Chrome DevTools on 9223 first.
"""
import sys, time, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from capture_web import Browser
b=Browser()
b.call('Page.enable')
b.call('Emulation.setDeviceMetricsOverride', {'width':1280,'height':1000,'deviceScaleFactor':1,'mobile':False})
b.call('Page.navigate', {'url':'http://127.0.0.1:8765'})
time.sleep(10)
b.js("document.querySelector('flt-semantics-placeholder')?.click()")
time.sleep(1)
b.shot('01-home-desktop')
b.text('Thêm thói quen')
b.shot('02-add-form')
b.text('Lưu thói quen')
assert 'Vui lòng nhập tên thói quen' in b.js('document.body.innerText')
b.shot('03-form-validation')
b.click(450,100)
b.call('Input.insertText', {'text':'Đi bộ kiểm tra web'})
b.click(450,215)
b.call('Input.insertText', {'text':'Dữ liệu thao tác kiểm tra thực tế trên Chrome.'})
b.text('Lưu thói quen')
time.sleep(1)
assert '5 thói quen dành cho bạn' in b.js('document.body.innerText')
def wheel(delta):
    b.call('Input.dispatchMouseEvent',{'type':'mouseWheel','x':700,'y':300,'deltaY':delta,'deltaX':0})
    time.sleep(1)
wheel(400)
b.click(400,416)
assert 'Đã hoàn thành 1/5 hôm nay' in b.js('document.body.innerText')
wheel(-500)
b.shot('04-home-completed')
b.click(425,772)
assert 'Chi tiết thói quen' in b.js('document.body.innerText')
b.shot('05-habit-detail')
b.text('Xóa thói quen')
b.shot('06-delete-confirmation')
b.text('Hủy')
b.text('Quay lại')
b.text('Thống kê 7 ngày')
assert 'Tổng: 1/5 lượt · 20%' in b.js('document.body.innerText')
b.shot('07-statistics')
b.text('Quay lại')
b.text('Thông tin nhóm')
b.shot('08-about-team')
b.text('Quay lại')
b.text('Đổi ngôn ngữ')
assert 'Change language' in b.js('document.body.innerText')
b.call('Emulation.setDeviceMetricsOverride',{'width':390,'height':844,'deviceScaleFactor':1,'mobile':True})
time.sleep(1)
b.shot('09-home-english-narrow')
b.call('Input.dispatchMouseEvent',{'type':'mouseWheel','x':190,'y':500,'deltaY':200,'deltaX':0})
time.sleep(1)
b.text('Add habit')
b.shot('10-form-english-narrow')
